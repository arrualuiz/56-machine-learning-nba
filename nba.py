"""# Preparação dos Dados

Foi realizada uma análise dos valores ausentes presentes no dataset. Como a quantidade de registros com valores faltantes representa uma pequena parcela da base de dados, optou-se pela remoção dessas observações para simplificar o processo de preparação dos dados.

Além disso, a variável categórica "Posicao" foi convertida para formato numérico utilizando a técnica One-Hot Encoding, permitindo sua utilização pelos algoritmos de Machine Learning.
"""

#removendo registros com valores ausentes

df = df.dropna()

