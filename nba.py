df.head()

"""# Definição das Variáveis

A variável WinShares foi definida como variável alvo, ou seja, o valor que o modelo buscará prever.

As demais variáveis do dataset foram utilizadas como atributos preditores.
"""

#separação entre variáveis preditoras (X) e variável alvo (y)

X = df.drop('WinShares', axis=1)
y = df['WinShares']

print(X.shape)
print(y.shape)

